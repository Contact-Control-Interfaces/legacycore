#!/usr/bin/env bash
# =============================================================================
# build-protobuf.sh
# -----------------------------------------------------------------------------
# Builds protobuf (protoc + static libprotobuf) from source and installs it
# into a prefix that CMake can find through -DCMAKE_PREFIX_PATH. On Windows it
# uses the MSYS2 MINGW64 toolchain (install.ps1 runs it); on Linux, the system
# gcc (build.sh runs it). CI uses both.
#
# Why from source: the repository used to carry protobuf.zip, prebuilt with
# GCC 13, which stopped working once MSYS2's libstdc++ dropped the
# std::call_once internals it referenced. A from-source build always matches
# the compiler in use.
#
# Run from an MSYS2 MINGW64 shell (install.ps1 does this for you), or on Linux:
#     tools/build-protobuf.sh [prefix]          # default prefix: ./protobuf
#
# The prefix gets a .build-stamp naming the protobuf version and the compiler.
# install.ps1 and build.ps1 compare it against the current compiler and rebuild
# when they differ.
# =============================================================================
set -euo pipefail

PROTOBUF_VERSION="3.21.12"
PROTOBUF_TAG="v21.12"
PROTOBUF_SHA256="4eab9b524aa5913c6fffb20b2a8abf5ef7f95a80bc0701f3a6dbb4c607f73460"
PROTOBUF_URL="https://github.com/protocolbuffers/protobuf/releases/download/${PROTOBUF_TAG}/protobuf-cpp-${PROTOBUF_VERSION}.tar.gz"

die() { echo "build-protobuf.sh: $*" >&2; exit 1; }

if [ "${MSYSTEM:-}" = "MINGW64" ]; then
    platform="MINGW64"
    install_hint="pacman -S --needed mingw-w64-x86_64-gcc mingw-w64-x86_64-cmake mingw-w64-x86_64-ninja"
    protoc="protoc.exe"
    # protoc is linked statically so it runs outside an MSYS2 shell (CLion, plain cmd).
    platform_flags=(-DCMAKE_EXE_LINKER_FLAGS="-static")
elif [ "$(uname -s)" = "Linux" ]; then
    platform="Linux"
    install_hint="sudo apt-get install build-essential cmake ninja-build curl (or your distribution's equivalent)"
    protoc="protoc"
    # The static libraries are linked into libcci.so, so they must be position-independent.
    platform_flags=(-DCMAKE_POSITION_INDEPENDENT_CODE=ON)
else
    die "run this from an MSYS2 MINGW64 shell or on Linux (MSYSTEM is '${MSYSTEM:-unset}', uname is '$(uname -s)')"
fi
for tool in gcc g++ cmake ninja tar sha256sum curl; do
    command -v "$tool" >/dev/null || die "'$tool' not found. Install it with: $install_hint"
done

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
prefix="${1:-$script_dir/../protobuf}"
mkdir -p "$prefix"
prefix="$(cd "$prefix" && pwd)"

# The prefix is emptied before installing, so it must be empty or already a
# protobuf install - never, say, the repository root from a mistyped argument.
if [ -n "$(ls -A "$prefix")" ] && [ ! -d "$prefix/include/google/protobuf" ]; then
    die "$prefix is not empty and does not look like a protobuf install - refusing to overwrite it"
fi

# On MSYS2 the C runtime changes independently of gcc, and libprotobuf.a is
# linked into libcci.dll against it, so its version is part of the stamp too.
runtime=""
if [ "$platform" = "MINGW64" ]; then
    runtime=" crt $(pacman -Q mingw-w64-x86_64-crt 2>/dev/null | cut -d' ' -f2)"
fi
stamp="protobuf ${PROTOBUF_VERSION} ${platform} gcc $(gcc -dumpfullversion)${runtime}"
if [ -f "$prefix/.build-stamp" ] && [ "$(cat "$prefix/.build-stamp")" = "$stamp" ]; then
    echo "protobuf is up to date in $prefix ($stamp)"
    exit 0
fi

# Object paths in protobuf's build tree are ~120 characters deep, and ar.exe
# fails ("No such file or directory") past Windows' 260-character limit. The
# default /tmp of a C:\msys64 install is short enough; for an MSYS2 under a
# deep path, point TMPDIR somewhere short.
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# /usr/bin/curl: on MSYS2 that is MSYS's own curl, not MINGW64's (first on PATH
# once cmake pulls it in): the MINGW64 CA bundle is generated by a pacman hook,
# and a fresh install has been seen with it empty, failing every HTTPS download
# with curl error 77.
echo "Downloading protobuf ${PROTOBUF_VERSION}"
/usr/bin/curl -fsSL --retry 3 -o "$work/src.tar.gz" "$PROTOBUF_URL"
echo "${PROTOBUF_SHA256}  $work/src.tar.gz" | sha256sum -c --quiet - || die "checksum mismatch for $PROTOBUF_URL"
tar -xzf "$work/src.tar.gz" -C "$work"

# Static libraries, so libcci.dll / libcci.so carries protobuf inside it.
# zlib is off: libcci does not use gzip streams, and leaving it on would make
# the result depend on whether mingw-w64-x86_64-zlib happens to be installed.
echo "Configuring"
cmake -G Ninja -S "$work/protobuf-${PROTOBUF_VERSION}" -B "$work/build" \
    -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX="$prefix" \
    "${platform_flags[@]}" \
    -Dprotobuf_BUILD_TESTS=OFF \
    -Dprotobuf_BUILD_SHARED_LIBS=OFF \
    -Dprotobuf_WITH_ZLIB=OFF \
    -Wno-dev

echo "Building"
cmake --build "$work/build"

# Install into a clean prefix: stale headers or libraries from an older
# compiler or a hand-installed protobuf must not survive next to the new ones.
find "$prefix" -mindepth 1 -delete
cmake --install "$work/build"

"$prefix/bin/$protoc" --version
echo "$stamp" > "$prefix/.build-stamp"
echo "protobuf installed in $prefix ($stamp)"
